"""Slice the user's transparent artwork; keep original tiles and editable bases."""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'design/references/service-tags.png'
DEST=ROOT/'dist/assets/service-tags/original'
DEST.mkdir(parents=True,exist_ok=True)
image=Image.open(SOURCE).convert('RGBA')
alpha=np.asarray(image.getchannel('A'))

def segments(values):
 indices=np.flatnonzero(values)
 return [(int(group[0]),int(group[-1])+1) for group in np.split(indices,np.flatnonzero(np.diff(indices)>1)+1) if len(group)]

IDS=[['smile','hourglass','film','film-cn','arrow','animation','star-square'],
 ['badge','web','web-cn','steps','soft-cross','video'],
 ['bowtie','visual','visual-cn','star-hex','marvlore','culture','clover','cgi']]
ICONS={'smile','hourglass','arrow','star-square','badge','steps','soft-cross','bowtie','star-hex','clover'}

def editable_base(tile):
 """Remove only isolated lettering inside the capsule; retain all edge pixels."""
 data=np.array(tile)
 height,width=data.shape[:2]
 fill=data[int(height*.14),width//2,:3].copy()
 x0,x1=int(width*.055),int(width*.945)
 y0,y1=int(height*.19),int(height*.81)
 difference=np.max(np.abs(data[:,:,:3].astype(int)-fill.astype(int)),axis=2)
 mask=(difference>2)&(data[:,:,3]>0)
 mask[:y0]=False;mask[y1:]=False;mask[:,:x0]=False;mask[:,x1:]=False
 visited=np.zeros(mask.shape,dtype=bool)
 removed=0
 for y,x in zip(*np.where(mask)):
  if visited[y,x]:continue
  stack=[(int(y),int(x))];visited[y,x]=True;component=[];boundary=False
  while stack:
   py,px=stack.pop();component.append((py,px))
   if px in (x0,x1-1) or py in (y0,y1-1):boundary=True
   for ny,nx in ((py-1,px),(py+1,px),(py,px-1),(py,px+1)):
    if 0<=ny<height and 0<=nx<width and mask[ny,nx] and not visited[ny,nx]:
     visited[ny,nx]=True;stack.append((ny,nx))
  if not boundary:
   for py,px in component:data[py,px,:3]=fill
   removed+=len(component)
 assert np.array_equal(data[:,:,3],np.asarray(tile)[:,:,3])
 return Image.fromarray(data),removed

manifest={}
bands=segments((alpha>0).any(axis=1))
assert len(bands)==len(IDS)
for ids,(top,bottom) in zip(IDS,bands):
 columns=segments((alpha[top:bottom]>0).any(axis=0))
 assert len(ids)==len(columns)
 for tag_id,(left,right) in zip(ids,columns):
  tile=image.crop((left,top,right,bottom))
  bbox=tile.getchannel('A').getbbox()
  tile=tile.crop(bbox)
  x,y=left+bbox[0],top+bbox[1]
  tile.save(DEST/f'{tag_id}.png')
  info={'x':x,'y':y,'width':tile.width,'height':tile.height,'asset':f'./assets/service-tags/original/{tag_id}.png'}
  # These three supplied tiles contain intentional grey square textures in RGB.
  # Retain the untouched RGBA original and expose its RGB artwork on black too.
  if tag_id in {'smile','star-square','clover'}:
   tile.convert('RGB').save(DEST/f'{tag_id}-display.png')
   info['displayAsset']=f'./assets/service-tags/original/{tag_id}-display.png'
  if tag_id not in ICONS:
   background,removed=editable_base(tile)
   assert removed>0,tag_id
   background.save(DEST/f'{tag_id}-background.png')
   info['background']=f'./assets/service-tags/original/{tag_id}-background.png'
   print(f'{tag_id}: original contour retained; {removed} lettering pixels cleared')
  manifest[tag_id]=info

(ROOT/'dist/service-tag-assets.js').write_text('// Generated by scripts/slice-service-tags.py from the original transparent artwork.\nexport const serviceTagCanvas='+json.dumps({'width':image.width,'height':image.height})+';\nexport const serviceTagAssets='+json.dumps(manifest,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print(f'Saved {len(manifest)} independent original tiles and editable capsule backgrounds.')
