#!/usr/bin/env node
/**
 * Optional media CDN prefix for dist/assets (fonts, images, video).
 *
 * Default: empty → keep relative ./assets/ (same-origin here.now + Cloudflare).
 * Set MEDIA_CDN_BASE or deployment.json "mediaCdnBase" to an origin
 * (e.g. https://media.example.com) to rewrite ./assets/ → {base}/assets/.
 *
 * App shell (HTML/JS/CSS modules) stays on the site origin; only media paths move.
 *
 * Usage:
 *   node scripts/apply-media-cdn.mjs
 *   MEDIA_CDN_BASE=https://cdn.example.com node scripts/apply-media-cdn.mjs
 */
import {readFileSync, writeFileSync, readdirSync, statSync} from 'node:fs';
import {dirname, extname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const TEXT_EXTS = new Set(['.js', '.mjs', '.css', '.html']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const path = join(dir, name);
    const st = statSync(path);
    if (st.isDirectory()) walk(path, out);
    else out.push(path);
  }
  return out;
}

function readBase() {
  const fromEnv = (process.env.MEDIA_CDN_BASE || '').trim();
  if (fromEnv) return fromEnv.replace(/\/$/, '');
  try {
    const deployment = JSON.parse(readFileSync(join(ROOT, 'deployment.json'), 'utf8'));
    return String(deployment.mediaCdnBase || '').trim().replace(/\/$/, '');
  } catch {
    return '';
  }
}

function injectMediaCdnModule(base) {
  const file = join(DIST, 'media-cdn.js');
  const body =
    '// Optional media CDN base. Empty = same-origin (here.now / local).\n' +
    '// Generated by scripts/apply-media-cdn.mjs — do not hand-edit the constant.\n' +
    'export const MEDIA_CDN_BASE = ' + JSON.stringify(base) + ';\n' +
    '\n' +
    '/** @param {string} relative path like ./assets/foo.webp or assets/foo.webp or foo.webp under assets */\n' +
    'export function assetUrl(relative) {\n' +
    "  const cleaned = String(relative || '').replace(/^\\.\\//, '');\n" +
    "  const path = cleaned.startsWith('assets/') ? cleaned : ('assets/' + cleaned);\n" +
    '  if (!MEDIA_CDN_BASE) return "./" + path;\n' +
    "  return MEDIA_CDN_BASE.replace(/\\/$/, '') + '/' + path;\n" +
    '}\n';
  writeFileSync(file, body);
}

function rewriteAssets(text, base) {
  if (!base) return {text, count: 0};
  let count = 0;
  const next = text.replace(/(?<![A-Za-z0-9:/])\.\/assets\//g, () => {
    count += 1;
    return base + '/assets/';
  });
  return {text: next, count};
}

function main() {
  const base = readBase();
  injectMediaCdnModule(base);

  let filesChanged = 0;
  let replacements = 0;
  if (base) {
    for (const file of walk(DIST)) {
      if (!TEXT_EXTS.has(extname(file).toLowerCase())) continue;
      if (relative(DIST, file) === 'media-cdn.js') continue;
      const raw = readFileSync(file, 'utf8');
      const {text, count} = rewriteAssets(raw, base);
      if (!count) continue;
      writeFileSync(file, text);
      filesChanged += 1;
      replacements += count;
    }
  }

  console.log(
    base
      ? 'media-cdn: base=' + base + ' rewrote ' + replacements + ' refs in ' + filesChanged + ' files'
      : 'media-cdn: base empty → same-origin ./assets/ (here.now)',
  );
}

main();
